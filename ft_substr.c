#include "libft.h"

char	*ft_substr(char const *s, unsigned int start, size_t len)
{
	char	*str;
	size_t	i;
	size_t	j;

	*str = (char *)malloc(sizeof(*s) * len + 1);
	i = 0;
	j = 0;
	if(!str)
		return(NULL);
	while(s[i] != '\0')
	{
		if (i >= start && j < len)
		{
			str[j] = s[i];
			j++;
		}
		i++;
	}
	str[j] = 0;
	return (*str);
}
